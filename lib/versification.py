def _psalter(name: str) -> dict:
    table = {}
    for entry in PSALTERS[name].split(";"):
        psalm, rows = entry.strip().split(":")
        verses = {}
        for row in rows.split("|"):
            v, eng = row.split("=")
            lo, _, hi = eng.partition("-")
            verses[int(v)] = (int(lo), int(hi or lo))
        table[int(psalm)] = verses
    return table


_PSALTER_TABLES: dict = {}


def psalter_verse(name: str, psalm: int, verse: int, end: bool = False) -> int:
    """The English verse of a psalter's: the first it holds, or with `end` the last."""
    if name not in _PSALTER_TABLES:
        _PSALTER_TABLES[name] = _psalter(name)
    lo, hi = _PSALTER_TABLES[name].get(psalm, {}).get(verse, (verse, verse))
    return hi if end else lo


def psalter_citation(citation: str, name: str) -> str:
    """A citation's psalms from a psalter's verses (PSALTERS) into the English
    ones: a range's first verse to the first English verse it holds, its last
    to the last, a lone verse to all of them ("13" -> "13–14")."""
    out = []
    pos = 0
    psalm = False
    chapter = None
    for m in TOKEN.finditer(citation):
        gap = citation[pos:m.start()]
        out.append(gap)
        pos = m.end()
        # After "; " or "–end" the next bare number is another psalm.
        if ";" in gap or "end" in gap:
            chapter = None
        if m.group("book"):
            psalm = m.group("book") in ("Psalm", "Psalms")
            chapter = None
            out.append(m.group(0))
            continue
        n = int(m.group("num"))
        if m.group("colon") or not psalm or chapter is None:
            if m.group("colon"):
                chapter = n
            out.append(m.group(0))
            continue
        starts = re.match(r"\s*[–-]", citation[pos:]) is not None
        ends = "".join(out).rstrip().endswith(("–", "-"))
        first, last = psalter_verse(name, chapter, n), psalter_verse(name, chapter, n, True)
        if ends:
            out.append(f"{last}{m.group('letter')}")
        elif starts or first == last:
            out.append(f"{first}{m.group('letter')}")
        else:
            out.append(f"{first}–{last}")
    out.append(citation[pos:])
    return "".join(out)


def numbering_books(setting: str):
    """A church's `verse_numbering` setting as the books it numbers the Hebrew
    way: None for none (the English numbering), "all" for every book, else a
    set of book names ("Psalms Joel")."""
    words = str(setting or "").replace(",", " ").split()
    if not words or words == ["english"]:
        return None
    if "hebrew" in words or "all" in words:
        return "all"
    return {"Psalms" if w in ("Psalm", "Psalms") else w.replace("_", " ") for w in words}


def convert(citation: str, books="all") -> str:
    """Rewrite a citation from Hebrew to English numbering, keeping its layout.

    Reads left to right: a book name sets the book, "N:" a chapter, other
    numbers are verses of the current chapter.  A verse that moves to another
    chapter is written with its chapter, and the following verses of the same
    range follow it ("Joel 3:1–5" -> "Joel 2:28–32", "Malachi 3:19–24" ->
    "Malachi 4:1–6").  `books`: "all", or the set of books to convert
    (numbering_books); the others are left as they are."""
    out = []
    active = True
    pos = 0
    book = None
    chapter = None
    cur_ch = None          # the chapter the output is in, for verses that move
    whole = re.fullmatch(r"\s*(Psalm|Psalms)\s+(\d+)\s*", citation)
    if whole:
        return citation    # a whole psalm is the same psalm
    for m in TOKEN.finditer(citation):
        out.append(citation[pos:m.start()])
        pos = m.end()
        if m.group("book"):
            book = m.group("book")
            chapter = cur_ch = None
            active = books == "all" or ("Psalms" if book in ("Psalm", "Psalms") else book) in books
            out.append(m.group(0))
            continue
        if not active:
            out.append(m.group(0))
            continue
        n = int(m.group("num"))
        if m.group("colon"):
            # "N:" is a chapter; look ahead at its first verse to know where it lands.
            chapter = n
            nxt = re.match(r"\(?(\d+)", citation[pos:])
            if book and nxt:
                ech, _ = to_english(book, chapter, int(nxt.group(1)))
            else:
                ech = chapter
            # "8:23–9:6" in Hebrew is all of English chapter 9: no second "9:".
            if ech == cur_ch and "".join(out).rstrip().endswith(("–", "-")):
                continue
            cur_ch = ech
            out.append(f"{ech}:")
            continue
        if book is None or chapter is None:
            out.append(m.group(0))
            continue
        ech, ev = to_english(book, chapter, n)
        if ech != cur_ch:
            # The verse lands in another English chapter: name it.
            out.append(f"{ech}:{ev}{m.group('letter')}")
            cur_ch = ech
        else:
            out.append(f"{ev}{m.group('letter')}")
    out.append(citation[pos:])
    return "".join(out)


