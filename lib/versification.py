# left as it is (the half verse cannot be told apart in a citation).


def to_english(book: str, chapter: int, verse: int) -> tuple[int, int]:
    """The English chapter and verse of a Hebrew one."""
    if book in ("Psalm", "Psalms"):
        return chapter, max(1, verse - PSALM_HEADING.get(chapter, 0))
    for ch, lo, hi, ech, shift in SHIFTS.get(book, ()):
        if chapter == ch and lo <= verse <= hi:
            return ech, verse + shift
    return chapter, verse


